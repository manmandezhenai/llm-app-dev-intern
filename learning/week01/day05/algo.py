"""
题目名称：移除元素
题目描述：给你一个数组 nums 和一个值 val，你需要原地移除所有数值等于 val 的元素，并返回移除后数组的新长度。
不要使用额外的数组空间，你必须仅使用 O(1) 额外空间并原地修改输入数组。
元素的顺序可以改变。你不需要考虑数组中超出新长度后面的元素。

解题思路：
采用快慢双指针法原地修改数组：
1. 初始化慢指针slow=0，指向新数组的下一个插入位置
2. 快指针fast遍历数组所有元素
3. 当fast指向的元素不等于目标值val时，将该元素赋值给slow位置，slow向后移动一位
4. 当fast指向的元素等于val时，直接跳过，不处理
5. 遍历结束后，slow的值就是移除后数组的新长度
该方法无需额外空间，原地修改数组，是数组移除类问题的标准解法

时空复杂度：
- 时间复杂度：O(n)，n为数组长度，快指针遍历整个数组一次
- 空间复杂度：O(1)，只使用两个指针变量，常数级额外空间
"""


def remove_element(nums, val):
    """
    原地移除数组中所有等于val的元素，返回新数组长度
    :param nums: 输入整数数组
    :param val: 要移除的目标值
    :return: 移除后数组的新长度
    """
    slow = 0
    for fast in range(0, len(nums)):
        if nums[fast] != val:
            nums[slow] = nums[fast]
            slow += 1

    return slow


if __name__ == '__main__':
    # 测试用例1：多个目标元素
    print(f"测试用例1：{remove_element([3, 2, 2, 3], 3)}")

    # 测试用例2：分散的目标元素
    print(f"测试用例2：{remove_element([0, 1, 2, 2, 3, 0, 4, 2], 2)}")

    # 测试用例3：空数组
    print(f"测试用例3：{remove_element([], 0)}")

    # 测试用例4：全是目标元素
    print(f"测试用例4：{remove_element([5, 5, 5], 5)}")
