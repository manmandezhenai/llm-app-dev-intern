"""
题目名称：搜索插入位置
题目描述：给定一个排序数组 nums 和一个目标值 target，在数组中找到目标值，并返回其索引。
如果目标值不存在于数组中，返回它将会被按顺序插入的位置。
你可以假设数组中无重复元素。

解题思路：
采用线性遍历法，利用数组有序的特性：
1. 遍历数组的每个元素及其下标
2. 找到第一个大于等于target的元素，其下标就是目标位置（存在则匹配，不存在则插入）
3. 如果遍历完所有元素都小于target，说明target最大，插入到数组末尾，返回数组长度
该方法逻辑简单直观，适合入门理解数组遍历与边界处理

时空复杂度：
- 时间复杂度：O(n)，n为数组长度，最坏情况遍历整个数组
- 空间复杂度：O(1)，只使用常数级别的额外变量
"""


def search_insert(nums, target):
    """
    在有序数组中查找目标值的位置，不存在则返回插入位置
    :param nums: 有序无重复整数数组
    :param target: 目标整数
    :return: 目标值的索引或插入位置
    """
    for i, num in enumerate(nums):
        if num >= target:
            return i

    return len(nums)


if __name__ == '__main__':
    # 测试用例1：目标值存在于数组中
    print(f"测试用例1：{search_insert([1, 3, 5, 6], 5)}")

    # 测试用例2：目标值不存在，插入中间
    print(f"测试用例2：{search_insert([1, 3, 5, 6], 2)}")

    # 测试用例3：目标值大于所有元素，插入末尾
    print(f"测试用例3：{search_insert([1, 3, 5, 6], 7)}")

    # 测试用例4：目标值大于所有元素，插入开头
    print(f"测试用例4：{search_insert([1, 3, 5, 6], 0)}")
