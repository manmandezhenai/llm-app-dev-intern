"""
题目名称：有效的括号
题目描述：给定一个只包括 '('，')'，'{'，'}'，'['，']' 的字符串 s ，判断字符串是否有效。
有效字符串需满足：
1. 左括号必须用相同类型的右括号闭合。
2. 左括号必须以正确的顺序闭合。
3. 每个右括号都有一个对应的相同类型的左括号。

解题思路：
使用栈结构解决括号匹配问题，Python中用列表模拟栈：
1. 构建右括号到左括号的映射字典，用于快速匹配对应关系
2. 遍历字符串中的每个字符：
   - 如果是左括号，压入栈中
   - 如果是右括号，检查栈是否为空或栈顶是否为对应左括号
   - 栈空或不匹配则直接返回False，匹配则弹出栈顶
3. 遍历结束后，栈为空说明所有括号都正确匹配，返回True
栈结构天然适合处理嵌套、匹配类问题，是本题最优基础解法

时空复杂度：
- 时间复杂度：O(n)，n为字符串长度，每个字符最多入栈出栈一次
- 空间复杂度：O(n)，最坏情况全为左括号，栈存储所有字符
"""


def is_valid(s):
    """
    判断输入的括号字符串是否有效
    :param s: 只包含括号的字符串
    :return: 布尔值，有效返回True，无效返回False
    """
    # 右括号到左括号的映射
    bracket_map = {')': '(', ']': '[', '}': '{'}
    stack = []

    for char in s:
        # 左括号入栈
        if char in bracket_map.values():
            stack.append(char)
        # 右括号匹配校验
        else:
            # 栈空或不匹配则无效
            if not stack or stack[-1] != bracket_map[char]:
                return False
            stack.pop()

    # 栈空说明全部匹配完成
    return len(stack) == 0


if __name__ == '__main__':
    # 测试用例1：简单有效括号
    print(f"测试用例1：{is_valid('()')}")

    # 测试用例2：多种类有效括号
    print(f"测试用例2：{is_valid('()[]{}')}")

    # 测试用例3：类型不匹配
    print(f"测试用例3：{is_valid('(]')}")

    #  测试用例4：顺序不匹配
    print(f"测试用例4：{is_valid('([)]')}")
