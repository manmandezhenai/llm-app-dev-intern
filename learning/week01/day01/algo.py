"""
题目名称：两数之和
题目描述：给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出和为目标值 target 的那两个整数，并返回它们的数组下标。
你可以假设每种输入只会对应一个答案，并且你不能使用相同的元素。
你可以按任意顺序返回答案。

解题思路：
采用暴力枚举法，通过两层循环遍历数组：
1. 外层循环遍历数组每个元素，下标为i
2. 内层循环从i+1的位置开始向后遍历，下标为j
3. 判断 nums[i] + nums[j] 是否等于目标值target
4. 相等则直接返回下标列表[i, j]，遍历结束未找到返回空列表
该方法逻辑简单直观，适合入门理解数组遍历与基础判断逻辑

时空复杂度：
- 时间复杂度：O(n²)，n为数组长度，最坏情况两层循环遍历所有元素
- 空间复杂度：O(1)，只使用常数级别的额外变量
"""


def two_sum(nums, target):
    """
    两数之和：找出数组中和为目标值的两个数的下标
    :param nums: 整数数组
    :param target: 目标值
    :return: 两个数的下标列表
    """
    for i in range(len(nums)):
        for j in range(i + 1, len(nums)):
            if nums[i] + nums[j] == target:
                return [i, j]

    return []


if __name__ == '__main__':
    # 测试用例1：基础正整数场景
    print(f"测试用例1：{two_sum([2, 7, 11, 15], 9)}")

    # 测试用例2：非顺序匹配场景
    print(f"测试用例2：{two_sum([3, 2, 4], 6)}")

    # 测试用例3：相同元素场景
    print(f"测试用例3：{two_sum([3, 3], 6)}")

    # 测试用例4：负数场景
    print(f"测试用例4：{two_sum([-1, -2, -3, -4, -5], -7)}")
